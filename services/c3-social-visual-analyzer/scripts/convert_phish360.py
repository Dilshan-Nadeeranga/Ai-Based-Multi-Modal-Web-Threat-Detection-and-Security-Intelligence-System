"""Convert a balanced subset of the Phish360 Parquet files into evidence folders.

Phish360 (Multimodal-Phishing-Benchmarks) ships ``Phish360_legit.parquet`` and
``Phish360_phish.parquet``: one row per webpage with URL, label, target brand
and extracted page text. Screenshots are referenced by ``image_path`` but are
not inside the Parquet files; pass ``--images-root`` if they were downloaded.

Each selected row becomes ``<out>/legit/P360_<folder>/`` or
``<out>/scam/P360_<folder>/`` holding ``post_info.txt``, ``caption.txt`` (page
text) and ``post1.png`` when a screenshot is available. Import the result with
``scripts/import_evidence.py``. Existing folders are never overwritten.

The URLs are real phishing links: they are written as text only and are never
visited by this script. Do not open them in a browser.

    python scripts/convert_phish360.py "D:\\Reasearch\\Datasets\\Phish36011k" "D:\\Reasearch\\ScamTrace_Evidence"
    python scripts/convert_phish360.py <parquet_dir> <out> --per-class 200 --language any
"""

from __future__ import annotations

import argparse
import hashlib
import random
import shutil
import sys
from pathlib import Path, PureWindowsPath

from _bootstrap import load_settings, setup

from app.utils.url_utils import normalize_evidence_url

COLUMNS = ["folder_name", "Class", "brand", "URL", "Domain", "image_path",
           "trafilatura_text", "html_text_language"]
GENERIC_BRANDS = {"", "unknown", "phish", "other"}
SOURCE_DATASET = "Phish360 (Multimodal-Phishing-Benchmarks)"
FOLDER_PREFIX = "P360_"


def _load_rows(path: Path) -> list[dict]:
    try:
        import pyarrow.parquet as pq
    except ImportError as exc:  # pragma: no cover - depends on the environment
        raise SystemExit("ERROR: pyarrow is required: pip install -r requirements.txt") from exc
    return pq.read_table(path, columns=COLUMNS).to_pylist()


def eligible(rows: list[dict], language: str, max_text: int) -> list[dict]:
    """Rows with a valid URL and page text, one per domain and per identical text."""
    seen_domains: set[str] = set()
    seen_texts: set[str] = set()
    result = []
    for row in rows:
        text = (row.get("trafilatura_text") or "").strip()
        if not text:
            continue
        if language != "any" and (row.get("html_text_language") or "").lower() != language.lower():
            continue
        try:
            url = normalize_evidence_url((row.get("URL") or "").strip())
        except ValueError:
            continue
        domain = (row.get("Domain") or "").lower()
        digest = hashlib.sha256(text.encode("utf-8")).hexdigest()
        if domain in seen_domains or digest in seen_texts:
            continue
        seen_domains.add(domain)
        seen_texts.add(digest)
        result.append({**row, "URL": url, "trafilatura_text": text[:max_text]})
    return result


def post_info(row: dict, scam: bool) -> str:
    brand = (row.get("brand") or "").strip()
    claimed = "" if brand.lower() in GENERIC_BRANDS else brand
    lines = [
        "# Generated by scripts/convert_phish360.py - Phish360 public dataset row",
        "# caption.txt holds the extracted webpage text (trafilatura), not a social post caption.",
        "# The URL is a real dataset URL: do NOT open it.",
        "platform: website",
        f"is_scam: {1 if scam else 0}",
        f"scam_type: {'phishing' if scam else 'legitimate'}",
        "label_status: verified",
        f"urls: {row['URL']}",
        f"claimed_brand: {claimed}",
        "collection_method: public_dataset",
        f"source_dataset: {SOURCE_DATASET}",
        f"source_reference: {row['folder_name']}",
        f"notes: Label from Phish360 annotation (class={row['Class']}, brand={brand or 'unknown'})",
    ]
    return "\n".join(lines) + "\n"


def _attach_screenshot(row: dict, folder: Path, images_root: Path | None) -> bool:
    """Copy the row's screenshot as post1.* unless the folder already has one or was imported."""
    if images_root is None or not row.get("image_path"):
        return False
    if (folder / "imported.txt").exists() or any(folder.glob("post1.*")):
        return False
    source = images_root.joinpath(*PureWindowsPath(row["image_path"]).parts)
    if not source.is_file():
        return False
    shutil.copyfile(source, folder / f"post1{source.suffix.lower() or '.png'}")
    return True


def write_folder(row: dict, scam: bool, out: Path, images_root: Path | None) -> tuple[bool, bool]:
    """Create one evidence folder (existing ones only gain a missing screenshot).

    Returns (created, screenshot_copied).
    """
    folder = out / ("scam" if scam else "legit") / f"{FOLDER_PREFIX}{row['folder_name']}"
    if folder.exists():
        return False, _attach_screenshot(row, folder, images_root)
    folder.mkdir(parents=True)
    (folder / "post_info.txt").write_text(post_info(row, scam), encoding="utf-8")
    (folder / "caption.txt").write_text(row["trafilatura_text"] + "\n", encoding="utf-8")
    return True, _attach_screenshot(row, folder, images_root)


def _parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description="Convert a Phish360 subset into evidence folders.")
    parser.add_argument("parquet_dir", type=Path, help="Folder with Phish360_legit.parquet and Phish360_phish.parquet")
    parser.add_argument("out", type=Path, help="Evidence folder (legit/ and scam/ are created inside)")
    parser.add_argument("--per-class", type=int, default=100, help="Rows to take from each class (default 100)")
    parser.add_argument("--seed", type=int, default=42, help="Random seed for a reproducible subset")
    parser.add_argument("--language", default="English", help="Page language to keep, or 'any' (default English)")
    parser.add_argument("--images-root", type=Path,
                        help="Folder that contains the 'Phish360\\trainval\\...' screenshot tree, if downloaded")
    parser.add_argument("-v", "--verbose", action="store_true", help="Show INFO logs")
    return parser


def main(argv: list[str] | None = None) -> int:
    args = _parser().parse_args(argv)
    setup(args.verbose)
    if args.per_class < 1:
        print("ERROR: --per-class must be at least 1", file=sys.stderr)
        return 2
    files = {"legit": args.parquet_dir / "Phish360_legit.parquet", "phish": args.parquet_dir / "Phish360_phish.parquet"}
    missing = [str(p) for p in files.values() if not p.is_file()]
    if missing:
        print(f"ERROR: not found: {', '.join(missing)}", file=sys.stderr)
        return 2
    if args.images_root is not None and not args.images_root.is_dir():
        print(f"ERROR: --images-root not found: {args.images_root}", file=sys.stderr)
        return 2

    max_text = load_settings().dataset_max_text_length
    out = args.out.expanduser().resolve()
    rng = random.Random(args.seed)
    for label, path in files.items():
        rows = eligible(_load_rows(path), args.language, max_text)
        chosen = rng.sample(rows, min(args.per_class, len(rows)))
        created = copied = 0
        for row in sorted(chosen, key=lambda r: r["folder_name"]):
            made, shot = write_folder(row, label == "phish", out, args.images_root)
            created += made
            copied += shot
        print(f"{label:5}: {len(rows)} eligible rows, {len(chosen)} selected, {created} new folder(s), "
              f"{copied} screenshot(s) copied")
    print(f"\nWritten to {out}\nNext: python scripts/import_evidence.py \"{out}\" --dry-run")
    return 0


if __name__ == "__main__":
    sys.exit(main())
