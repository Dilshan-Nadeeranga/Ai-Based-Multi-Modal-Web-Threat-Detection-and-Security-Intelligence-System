"""Convert a balanced subset of DIFrauD ``job_scams`` into evidence folders.

DIFrauD (Domain-Independent Fraud Detection benchmark, MIT licence) ships
``job_scams/{train,validation,test}.jsonl`` with ``{"text", "label"}`` rows:
job advertisements where ``label = 1`` marks a fraudulent posting. Fake jobs are
``financial_scam`` in this dataset (see docs/dataset_labels.md). The ads come
from a job board, so they are recorded as ``platform: website``; there are no
images.

Each selected row becomes ``<out>/difraud/legit|scam/DFD_<split>_<line>/`` with
``post_info.txt`` and ``caption.txt``. E-mail addresses and phone numbers are
replaced with ``[EMAIL]`` / ``[PHONE]``. Links are copied into ``urls:`` as text
and never visited. Existing folders are never overwritten. Import with
``scripts/import_evidence.py``.

    python scripts/convert_difraud.py "D:\\Reasearch\\Datasets\\DIFrauD\\job_scams" "D:\\Reasearch\\ScamTrace_Evidence"
    python scripts/convert_difraud.py <job_scams_dir> <out> --per-class 300 --seed 7
"""

from __future__ import annotations

import argparse
import hashlib
import json
import random
import re
import sys
from dataclasses import dataclass
from pathlib import Path

from _bootstrap import load_settings, setup

from app.utils.url_utils import extract_urls

SPLITS = ("train", "validation", "test")
SOURCE_DATASET = "DIFrauD job_scams"
FOLDER_PREFIX = "DFD_"
EMAIL_RE = re.compile(r"[\w.+-]+@[\w-]+(?:\.[\w-]+)+")
PHONE_RE = re.compile(r"(?<![\w/])\+?\(?\d[\d\s().-]{7,}\d(?![\w/])")
MIN_PHONE_DIGITS = 9


@dataclass(frozen=True)
class JobRow:
    split: str
    line: int
    text: str
    label: int

    @property
    def reference(self) -> str:
        return f"job_scams/{self.split}.jsonl:{self.line}"

    @property
    def folder_name(self) -> str:
        return f"{FOLDER_PREFIX}{self.split}_{self.line}"


def redact(text: str) -> str:
    text = EMAIL_RE.sub("[EMAIL]", text)
    return PHONE_RE.sub(
        lambda m: "[PHONE]" if sum(ch.isdigit() for ch in m.group()) >= MIN_PHONE_DIGITS else m.group(), text)


def read_rows(folder: Path) -> list[JobRow]:
    rows: list[JobRow] = []
    for split in SPLITS:
        path = folder / f"{split}.jsonl"
        if not path.is_file():
            continue
        for number, raw in enumerate(path.read_text(encoding="utf-8").splitlines(), start=1):
            if not raw.strip():
                continue
            try:
                item = json.loads(raw)
            except json.JSONDecodeError:
                continue
            text = item.get("text") if isinstance(item, dict) else None
            label = item.get("label") if isinstance(item, dict) else None
            if not isinstance(text, str) or not text.strip() or label not in (0, 1):
                continue
            rows.append(JobRow(split=split, line=number, text=text.strip(), label=label))
    return rows


def eligible(rows: list[JobRow], max_text: int) -> list[JobRow]:
    """Drop identical texts (keeping the first) and any text seen with both labels."""
    labels_by_digest: dict[str, set[int]] = {}
    for row in rows:
        labels_by_digest.setdefault(hashlib.sha256(row.text.encode("utf-8")).hexdigest(), set()).add(row.label)
    seen: set[str] = set()
    result: list[JobRow] = []
    for row in rows:
        digest = hashlib.sha256(row.text.encode("utf-8")).hexdigest()
        if digest in seen or len(labels_by_digest[digest]) > 1:
            continue
        seen.add(digest)
        result.append(JobRow(row.split, row.line, row.text[:max_text], row.label))
    return result


def post_info(row: JobRow, urls: list[str]) -> str:
    scam = row.label == 1
    lines = [
        "# Generated by scripts/convert_difraud.py - DIFrauD job_scams public dataset row",
        "# caption.txt holds a job advertisement (job board), not a social media caption.",
        "platform: website",
        f"is_scam: {1 if scam else 0}",
        f"scam_type: {'financial_scam' if scam else 'legitimate'}",
        "label_status: verified",
        f"urls: {' '.join(urls)}",
        "collection_method: public_dataset",
        f"source_dataset: {SOURCE_DATASET}",
        f"source_reference: {row.reference}",
        f"notes: Label from DIFrauD job_scams (label={row.label}: "
        f"{'fraudulent' if scam else 'genuine'} job posting)",
    ]
    return "\n".join(lines) + "\n"


def write_folder(row: JobRow, out: Path) -> bool:
    folder = out / ("scam" if row.label == 1 else "legit") / row.folder_name
    if folder.exists():
        return False
    caption = redact(row.text)
    folder.mkdir(parents=True)
    (folder / "post_info.txt").write_text(post_info(row, extract_urls(caption)), encoding="utf-8")
    (folder / "caption.txt").write_text(caption + "\n", encoding="utf-8")
    return True


def _parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description="Convert a DIFrauD job_scams subset into evidence folders.")
    parser.add_argument("job_scams_dir", type=Path, help="Folder with train.jsonl, validation.jsonl, test.jsonl")
    parser.add_argument("out", type=Path, help="Evidence folder (difraud/ is created inside)")
    parser.add_argument("--per-class", type=int, default=100, help="Rows to take from each class (default 100)")
    parser.add_argument("--seed", type=int, default=42, help="Random seed for a reproducible subset")
    parser.add_argument("-v", "--verbose", action="store_true", help="Show INFO logs")
    return parser


def main(argv: list[str] | None = None) -> int:
    args = _parser().parse_args(argv)
    setup(args.verbose)
    if args.per_class < 1:
        print("ERROR: --per-class must be at least 1", file=sys.stderr)
        return 2
    folder = args.job_scams_dir.expanduser().resolve()
    if not any((folder / f"{split}.jsonl").is_file() for split in SPLITS):
        print(f"ERROR: no {', '.join(s + '.jsonl' for s in SPLITS)} found in {folder}", file=sys.stderr)
        return 2

    rows = eligible(read_rows(folder), load_settings().dataset_max_text_length)
    out = args.out.expanduser().resolve() / "difraud"
    rng = random.Random(args.seed)
    for label, name in ((0, "legit"), (1, "scam")):
        pool = [row for row in rows if row.label == label]
        chosen = rng.sample(pool, min(args.per_class, len(pool)))
        created = sum(write_folder(row, out) for row in sorted(chosen, key=lambda r: (r.split, r.line)))
        short = f", only {len(pool)} available" if len(pool) < args.per_class else ""
        print(f"{name:5}: {len(pool)} eligible rows, {len(chosen)} selected, {created} new folder(s){short}")
    print(f"\nWritten to {out}\nNext: python scripts/import_evidence.py \"{out}\" --dry-run")
    return 0


if __name__ == "__main__":
    sys.exit(main())
