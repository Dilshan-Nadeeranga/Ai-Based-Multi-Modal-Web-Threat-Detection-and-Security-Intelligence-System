"""Verdict tiers, risk score and the evidence floor (thresholds in configs/verdict.yaml).

Part 9: Batch B-1 - end-to-end URL analysis engine.

Why three tiers (viva): a single argmax label hides how sure the model is. The fused
probability of "benign" is turned into

    risk_score = round(100 x (1 - P(benign)))
    Malicious   P(benign) < t_malicious   - the 9A threshold: <= 2 % of benign pages
                                            (out-of-fold) reach it, so a "Malicious"
                                            answer is rarely a false alarm
    Suspicious  P(benign) < t_suspicious  - the band where >= 95 % of OOF threat pages are
                                            caught; "have a closer look", not "block"
    Legitimate  otherwise

Both thresholds are fitted on the OUT-OF-FOLD probabilities of train+val only (the test
pages are only reported), separately for every subset of arms (see calibration.py):
when an arm is disabled or fails, its weight is shared out over the others, the
probability scale changes, and a degraded request must not reuse thresholds fitted for
four arms.

Why an evidence floor: the fused model is statistical and was trained on 391 pages. Some
evidence is near-certain on its own - a password form posting to another domain, code
that sends typed credentials or keystrokes to another site, a clipboard swapped for a
wallet address, a URL serving an .exe. If any such rule fires, the verdict is AT LEAST
Suspicious and the risk score at least the Suspicious floor, whatever the model says;
the response names the rule. The floor never LOWERS a verdict.
"""

from __future__ import annotations

import math
from dataclasses import dataclass, field
from typing import Any

from c2_analyzer.config import load_yaml_config
from c2_analyzer.fusion.common import ARM_ORDER

VERDICTS = ("Legitimate", "Suspicious", "Malicious")
GENERATED_MARKER = "# ---- generated by scripts/calibrate_verdict.py (do not edit below) ----"


def subset_key(arms) -> str:
    """'dom+behavior+text_tfidf' - arms in ARM_ORDER, the key of configs/verdict.yaml."""
    chosen = set(arms)
    return "+".join(arm for arm in ARM_ORDER if arm in chosen)


def risk_of(p_benign: float) -> int:
    """risk_score = round(100 x (1 - P(benign))), clipped to 0..100."""
    return int(min(100, max(0, round(100 * (1.0 - float(p_benign))))))


def risk_floor_of(benign_threshold: float) -> int:
    """The smallest risk score a page below ``benign_threshold`` can have (ceil)."""
    return int(min(100, max(0, math.ceil(100 * (1.0 - float(benign_threshold)) - 1e-9))))


@dataclass(frozen=True)
class Thresholds:
    """Tier cut-offs on P(benign) for one subset of arms."""

    arms: str
    malicious: float  # Malicious if P(benign) < this
    suspicious: float  # Suspicious if P(benign) < this (>= malicious)
    stats: dict[str, Any] = field(default_factory=dict)

    @property
    def malicious_risk(self) -> int:
        return risk_floor_of(self.malicious)

    @property
    def suspicious_risk(self) -> int:
        return risk_floor_of(self.suspicious)

    def as_dict(self) -> dict[str, Any]:
        return {
            "arms": self.arms,
            "malicious_below_p_benign": round(self.malicious, 6),
            "suspicious_below_p_benign": round(self.suspicious, 6),
            "malicious_min_risk": self.malicious_risk,
            "suspicious_min_risk": self.suspicious_risk,
        }


@dataclass(frozen=True)
class FloorRule:
    id: str
    modality: str
    kind: str  # dom_feature | behavior_pattern | fetch_download
    title: str
    implies: str | None = None
    features: tuple[str, ...] = ()
    pattern: str | None = None
    variants: tuple[str, ...] = ()


@dataclass(frozen=True)
class FloorHit:
    rule: FloorRule
    evidence: str | None = None  # domain / masked snippet


@dataclass
class VerdictPolicy:
    """configs/verdict.yaml: tier targets, floor rules, calibrated thresholds."""

    tiers: dict[str, float]
    rules: list[FloorRule]
    calibration: dict[str, Any]
    thresholds: dict[str, Thresholds]

    @classmethod
    def load(cls, raw: dict | None = None) -> VerdictPolicy:
        raw = raw if raw is not None else load_yaml_config("verdict")
        rules = [
            FloorRule(
                id=str(r["id"]),
                modality=str(r["modality"]),
                kind=str(r["kind"]),
                title=str(r["title"]),
                implies=r.get("implies"),
                features=tuple(r.get("features", ())),
                pattern=r.get("pattern"),
                variants=tuple(r.get("variants", ())),
            )
            for r in raw.get("floor_rules", [])
        ]
        thresholds = {
            key: Thresholds(
                arms=key,
                malicious=float(value["malicious_below_p_benign"]),
                suspicious=float(value["suspicious_below_p_benign"]),
                stats=dict(value.get("oof", {})),
            )
            for key, value in (raw.get("thresholds") or {}).items()
        }
        return cls(
            tiers=dict(raw.get("tiers", {})),
            rules=rules,
            calibration=dict(raw.get("calibration") or {}),
            thresholds=thresholds,
        )

    def for_arms(self, arms) -> Thresholds:
        key = subset_key(arms)
        if key not in self.thresholds:
            raise LookupError(
                f"no verdict thresholds for arms {key or '(none)'} - run "
                "scripts/calibrate_verdict.py"
            )
        return self.thresholds[key]


# ---- evidence floor ----------------------------------------------------------------------


def floor_hits(
    rules: list[FloorRule],
    dom_features: dict[str, float] | None = None,
    dom_evidence: dict[str, str] | None = None,
    behavior_findings: list[tuple[str, str, str | None]] | None = None,
    download_kind: str | None = None,
) -> list[FloorHit]:
    """The floor rules that fire for one page.

    ``behavior_findings`` = (pattern_id, variant, evidence) of Part 8; ``dom_evidence`` =
    feature -> short evidence text. A modality that did not run simply fires nothing.
    """
    hits: list[FloorHit] = []
    for rule in rules:
        if rule.kind == "dom_feature" and dom_features is not None and rule.features:
            if all(float(dom_features.get(name, 0) or 0) > 0 for name in rule.features):
                evidence = next(
                    (dom_evidence[f] for f in rule.features if dom_evidence and f in dom_evidence),
                    None,
                )
                hits.append(FloorHit(rule, evidence))
        elif rule.kind == "behavior_pattern" and behavior_findings:
            for pattern, variant, evidence in behavior_findings:
                if pattern == rule.pattern and (not rule.variants or variant in rule.variants):
                    hits.append(FloorHit(rule, evidence))
                    break
        elif rule.kind == "fetch_download" and download_kind:
            hits.append(FloorHit(rule, download_kind))
    return hits


# ---- decision ------------------------------------------------------------------------------


@dataclass
class Decision:
    verdict: str
    threat_class: str
    risk_score: int
    source: str  # "fusion" | "evidence_floor"
    fusion_verdict: str
    raised_by: list[str] = field(default_factory=list)  # floor rule ids that raised it
    supported_by: list[str] = field(default_factory=list)  # rules that fired (all)


def tier_of(p_benign: float, thresholds: Thresholds) -> str:
    if p_benign < thresholds.malicious:
        return "Malicious"
    if p_benign < thresholds.suspicious:
        return "Suspicious"
    return "Legitimate"


def most_probable_threat(probabilities: dict[str, float]) -> str:
    threats = {k: v for k, v in probabilities.items() if k != "benign"}
    return max(threats, key=lambda k: (threats[k], k)) if threats else "benign"


def decide(
    probabilities: dict[str, float] | None,
    thresholds: Thresholds | None,
    hits: list[FloorHit],
) -> Decision | None:
    """Verdict from fused probabilities + floor hits (None: nothing to decide on)."""
    fired = [hit.rule.id for hit in hits]
    if probabilities is None or thresholds is None:
        if not hits:
            return None
        # No model answered (e.g. an .exe URL has no page at all): the rules alone.
        implied = next((h.rule.implies for h in hits if h.rule.implies), "phishing")
        # ``thresholds`` = the full-arm set here: the floor's risk is a fixed number.
        risk = thresholds.suspicious_risk if thresholds else 50
        return Decision("Suspicious", implied, risk, "evidence_floor", "none", fired, fired)
    p_benign = float(probabilities.get("benign", 0.0))
    verdict = tier_of(p_benign, thresholds)
    risk = risk_of(p_benign)
    threat = most_probable_threat(probabilities)
    decision = Decision(
        verdict=verdict,
        threat_class="benign" if verdict == "Legitimate" else threat,
        risk_score=risk,
        source="fusion",
        fusion_verdict=verdict,
        supported_by=fired,
    )
    if hits and verdict == "Legitimate":
        decision.verdict = "Suspicious"
        decision.source = "evidence_floor"
        decision.raised_by = fired
        decision.threat_class = next((h.rule.implies for h in hits if h.rule.implies), threat)
    if hits:
        decision.risk_score = max(decision.risk_score, thresholds.suspicious_risk)
    return decision
